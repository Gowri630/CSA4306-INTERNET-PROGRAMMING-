CREATE DATABASE IF NOT EXISTS `01_flight_reservation_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `01_flight_reservation_db`;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('customer','admin') NOT NULL DEFAULT 'customer',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS flights (id INT AUTO_INCREMENT PRIMARY KEY, origin VARCHAR(80) NOT NULL, destination VARCHAR(80) NOT NULL, flight_date DATE NOT NULL, cabin_class VARCHAR(40) NOT NULL DEFAULT 'Economy', fare DECIMAL(10,2) NOT NULL, seats_available INT NOT NULL DEFAULT 20, flight_code VARCHAR(20) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS bookings (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, item_id INT NOT NULL,
 item_name VARCHAR(160) NOT NULL, details VARCHAR(255) NOT NULL DEFAULT '',
 amount DECIMAL(10,2) NOT NULL DEFAULT 0, status VARCHAR(40) NOT NULL DEFAULT 'Confirmed',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS feedback (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, name VARCHAR(120) NOT NULL,
 message TEXT NOT NULL, rating TINYINT NOT NULL DEFAULT 5, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);
